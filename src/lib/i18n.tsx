const STORAGE_KEY = "findable:language";

type Ctx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string, fallback: string) => string;
  tf: (key: string, fallback: string, vars: Record<string, string | number>) => string;
};

const LanguageContext = createContext<Ctx | null>(null);

function format(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    try {
      const raw = window.localStorage.getItem(STORAGE_KEY) as Lang | null;
      if (raw && LANGUAGES.some((l) => l.code === raw)) {
        setLangState(raw);
        document.documentElement.lang = raw;
      }
    } catch {
      /* noop */
    }
  }, []);

  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      window.localStorage.setItem(STORAGE_KEY, l);
      document.documentElement.lang = l;
    } catch {
      /* noop */
    }
  };

  const t = (key: string, fallback: string) => DICT[lang]?.[key] ?? fallback;
  const tf = (
    key: string,
    fallback: string,
    vars: Record<string, string | number>,
  ) => format(DICT[lang]?.[key] ?? fallback, vars);

  return (
    <LanguageContext.Provider value={{ lang, setLang, t, tf }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) {
    // Fallback when used outside provider (SSR, tests)
    return {
      lang: "en" as Lang,
      setLang: () => {},
      t: (_k: string, fallback: string) => fallback,
      tf: (_k: string, fallback: string, vars: Record<string, string | number>) =>
        format(fallback, vars),
    };
  }
  return ctx;
}